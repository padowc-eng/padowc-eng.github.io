function J = trimCost(x,V,p)

f = x(1);
pitchPlane = x(2);
rollPlane = x(3);

pitchLimit = deg2rad(45);
rollLimit = deg2rad(45);

if f < 15 || f > 90 || ...
        abs(pitchPlane) > pitchLimit || ...
        abs(rollPlane) > rollLimit

    J = 1e3;

    J = J + ...
        max(15-f,0)^2 + ...
        max(f-90,0)^2;

    J = J + ...
        100*max(abs(pitchPlane)-pitchLimit,0)^2;

    J = J + ...
        100*max(abs(rollPlane)-rollLimit,0)^2;

    return
end

Fwing = meanWingForce( ...
    f,pitchPlane,rollPlane,V,p);

Fnet = ...
    Fwing + ...
    bodyDrag(V,p) + ...
    [0;0;-p.m*p.g];

J = ...
    sum((Fnet/(p.m*p.g)).^2);

end


function Fmean = meanWingForce( ...
    f,pitchPlane,rollPlane,V,p)

theta = ...
    linspace(0,2*pi,p.Ntrim+1);

theta(end) = [];

F = zeros(3,p.Ntrim);

for i = 1:p.Ntrim

    FR = wingAerodynamics( ...
        theta(i), ...
        f,pitchPlane,rollPlane, ...
        V,1,p);

    FL = wingAerodynamics( ...
        theta(i), ...
        f,pitchPlane,rollPlane, ...
        V,-1,p);

    F(:,i) = FR + FL;

end

Fmean = mean(F,2);

end


function [Fwing,fPrime,kin] = ...
    wingAerodynamics( ...
    theta,f,pitchPlane,rollPlane,Vbody,side,p)

kin = wingKinematics( ...
    theta,f,pitchPlane,rollPlane,side,p);

fPrime = zeros(3,p.Nspan);

for i = 1:p.Nspan

    v = ...
        Vbody + ...
        p.r(i)*kin.vDirection;

    vPerp = ...
        v - kin.er*dot(kin.er,v);

    U = norm(vPerp);

    if U < 1e-8

        fPrime(:,i) = 0;
        continue

    end

    eV = vPerp/U;

    eDrag = -eV;

    eLift = ...
        side*cross(eV,kin.er);

    nLift = norm(eLift);

    if nLift < 1e-8

        fPrime(:,i) = 0;
        continue

    end

    eLift = eLift/nLift;

    q = ...
        0.5*p.rho*U^2;

    CL = ...
        p.CLmax* ...
        sin(2*kin.alpha)* ...
        (1 + ...
        p.camberLiftGain* ...
        abs(kin.camberState)* ...
        p.camberMax);

    CD = ...
        p.CD0 + ...
        p.CDalpha*sin(kin.alpha)^2 + ...
        p.CDi*CL^2;

    lift = ...
        q*p.c(i)* ...
        CL*kin.flip*eLift;

    drag = ...
        q*p.c(i)* ...
        CD*eDrag;

    fPrime(:,i) = ...
        lift + drag;

end

Fwing = ...
    trapz(p.r,fPrime,2);

end


function kin = wingKinematics( ...
    theta,f,pitchPlane,rollPlane,side,p)

omega = 2*pi*f;

phi = ...
    p.phiAmp*sin(theta);

phiDot = ...
    p.phiAmp*omega*cos(theta);

dev = ...
    p.devAmp*cos(theta);

devDot = ...
    -p.devAmp*omega*sin(theta);

er0 = [ ...
    sin(phi)*cos(dev)
    side*cos(phi)*cos(dev)
    sin(dev)];

dEr_dPhi = [ ...
    cos(phi)*cos(dev)
    -side*sin(phi)*cos(dev)
    0];

dEr_dDev = [ ...
    -sin(phi)*sin(dev)
    -side*cos(phi)*sin(dev)
    cos(dev)];

Rplane = ...
    Ry(pitchPlane)*Rx(rollPlane);

er = ...
    Rplane*er0;

er = ...
    er/norm(er);

ePhi = ...
    Rplane*dEr_dPhi;

ePhi = ...
    ePhi/norm(ePhi);

eDev = ...
    Rplane*dEr_dDev;

eDev = ...
    eDev/norm(eDev);

vDirection = ...
    Rplane*( ...
    dEr_dPhi*phiDot + ...
    dEr_dDev*devDot);

speedRatio = ...
    abs(phiDot)/(p.phiAmp*omega);

alpha = ...
    p.alphaMin + ...
    (p.alphaMax-p.alphaMin)* ...
    speedRatio^0.55;

flip = ...
    tanh( ...
    p.reversalSharpness* ...
    cos(theta+p.pitchLead));

camberState = ...
    tanh( ...
    p.camberSharpness* ...
    cos(theta+p.camberLead));

pitchAngle = ...
    -side*flip*alpha;

kin.phi = phi;
kin.phiDot = phiDot;

kin.dev = dev;
kin.devDot = devDot;

kin.er = er;
kin.ePhi = ePhi;
kin.eDev = eDev;

kin.vDirection = vDirection;

kin.alpha = alpha;

kin.flip = flip;
kin.camberState = camberState;

kin.pitchAngle = pitchAngle;

end


function [Srig,Sflex,center,Fwing] = ...
    wingSurface( ...
    theta,f,pitchPlane,rollPlane,Vbody,side,p)

[Fwing,fPrime,kin] = ...
    wingAerodynamics( ...
    theta,f,pitchPlane,rollPlane, ...
    Vbody,side,p);

shoulder = [ ...
    0
    side*p.shoulderY
    p.shoulderZ];

center = zeros(p.Nspan,3);

%% RIGID HALF

for i = 1:p.iRigid

    center(i,:) = ...
        shoulder' + ...
        p.r(i)*kin.er';

end

%% FLEXIBLE HALF

idx = p.iRigid:p.Nspan;

qFlex = ...
    fPrime(:,idx);

qAxial = ...
    kin.er*(kin.er'*qFlex);

qFlex = ...
    qFlex-qAxial;

wx = beamDeflection( ...
    p.sFlex, ...
    qFlex(1,:)', ...
    p.EIFlex);

wy = beamDeflection( ...
    p.sFlex, ...
    qFlex(2,:)', ...
    p.EIFlex);

wz = beamDeflection( ...
    p.sFlex, ...
    qFlex(3,:)', ...
    p.EIFlex);

w = [wx wy wz];

hinge = ...
    shoulder + ...
    p.rRigid*kin.er;

centerFlex = ...
    hinge' + ...
    p.sFlex*kin.er' + ...
    w;

center(idx,:) = ...
    centerFlex;

%% WING SURFACE

Nc = 9;

eta = ...
    linspace(-0.5,0.5,Nc);

X = zeros(p.Nspan,Nc);
Y = zeros(p.Nspan,Nc);
Z = zeros(p.Nspan,Nc);

for i = 1:p.Nspan

    if i == 1

        spanDirection = ...
            center(i+1,:)-center(i,:);

    elseif i == p.Nspan

        spanDirection = ...
            center(i,:)-center(i-1,:);

    else

        spanDirection = ...
            center(i+1,:)-center(i-1,:);

    end

    spanDirection = ...
        spanDirection(:);

    spanDirection = ...
        spanDirection/norm(spanDirection);

    chord0 = ...
        kin.ePhi - ...
        spanDirection* ...
        dot(spanDirection,kin.ePhi);

    if norm(chord0) < 1e-8

        chord0 = kin.eDev;

    end

    chord0 = ...
        chord0/norm(chord0);

    chordDirection = ...
        rotateVector( ...
        chord0, ...
        spanDirection, ...
        kin.pitchAngle);

    chordDirection = ...
        chordDirection/ ...
        norm(chordDirection);

    normalDirection = ...
        cross( ...
        spanDirection, ...
        chordDirection);

    normalDirection = ...
        normalDirection/ ...
        norm(normalDirection);

    if p.r(i) <= p.rRigid

        flexRamp = 0;

    else

        flexRamp = ...
            ((p.r(i)-p.rRigid)/ ...
            (p.R-p.rRigid))^0.75;

    end

    camber = ...
        p.camberMax* ...
        kin.camberState* ...
        flexRamp;

    for j = 1:Nc

        chordPosition = ...
            eta(j)*p.c(i);

        camberShape = ...
            1-(2*eta(j))^2;

        camberOffset = ...
            camber* ...
            p.c(i)* ...
            camberShape;

        point = ...
            center(i,:)' + ...
            chordPosition*chordDirection + ...
            camberOffset*normalDirection;

        X(i,j) = point(1);
        Y(i,j) = point(2);
        Z(i,j) = point(3);

    end

end

rigidIndex = ...
    1:p.iRigid;

flexIndex = ...
    p.iRigid:p.Nspan;

Srig.X = X(rigidIndex,:);
Srig.Y = Y(rigidIndex,:);
Srig.Z = Z(rigidIndex,:);

Sflex.X = X(flexIndex,:);
Sflex.Y = Y(flexIndex,:);
Sflex.Z = Z(flexIndex,:);

end


function w = beamDeflection(r,q,EI)

r = r(:);
q = q(:);
EI = EI(:);

n = length(r);

M = zeros(n,1);

for i = 1:n-1

    x = r(i:end);

    M(i) = trapz( ...
        x, ...
        q(i:end).* ...
        (x-r(i)));

end

curvature = ...
    M./EI;

slope = ...
    cumtrapz(r,curvature);

w = ...
    cumtrapz(r,slope);

end


function F = bodyDrag(V,p)

speed = norm(V);

if speed < 1e-10

    F = zeros(3,1);
    return

end

F = ...
    -0.5* ...
    p.rho* ...
    speed* ...
    p.CdA.*V;

end


function R = Rx(a)

R = [ ...
    1 0 0
    0 cos(a) -sin(a)
    0 sin(a) cos(a)];

end


function R = Ry(a)

R = [ ...
    cos(a) 0 sin(a)
    0 1 0
    -sin(a) 0 cos(a)];

end


function v = rotateVector(v0,axis,angle)

axis = ...
    axis/norm(axis);

v = ...
    v0*cos(angle) + ...
    cross(axis,v0)*sin(angle) + ...
    axis*dot(axis,v0)*(1-cos(angle));

end